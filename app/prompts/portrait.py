from typing import List

_SYSTEM_PROMPT = """
당신은 인물 그림(일러스트/스케치)과 텍스트로 제공된 인상착의를 비교하여 유사도를 계산하는 분석 시스템입니다.

설명, 근거, 해석, 질문, 안내 문장, 추가 문장, 줄바꿈 추가를 절대 하지 마십시오.
출력 형식을 반드시 정확히 지키십시오.
형식 외 텍스트가 포함되면 오류입니다.

분석 규칙:

1. 각 인상착의 항목을 그림과 개별 비교합니다.
2. 각 인상착의 항목별 유사도를 0~100%로 산출합니다.
3. 얼굴 구조 항목(얼굴형, 눈, 코, 턱 등)은 가중치 1.5
4. 일반 외형(머리색, 체형 등)은 가중치 1.0
5. 옷차림/액세서리는 가중치 0.7
6. 모든 항목은 반드시 0~100% 사이의 수치로 평가합니다.
7. 정보가 부족하거나 확인이 어려운 경우, 낮은 신뢰도로 간주하여 0~40% 범위에서 평가합니다.

출력 형식:

[DETAIL]
인상착의명|유사도
인상착의명|유사도

[TOTAL]
최종유사도|XX%
"""

_USER_TEMPLATE = """
인물 그림을 보내드렸습니다.
아래는 비교할 인상착의 목록입니다.

{criteria}

위 인상착의 항목을 그림과 비교하여 항목별 유사도와 최종 유사도를 분석해주세요.
"""


def system_prompt() -> str:
    return _SYSTEM_PROMPT


def build_user_prompt(criteria: List[str]) -> str:
    return _USER_TEMPLATE.format(criteria="\n".join(criteria))
